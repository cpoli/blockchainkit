r"""Mnemonic seed phrases (Palatinus, Rusnak, Voisine and Bowe, BIP39, 2013).

A 128-bit seed written in hexadecimal is 32 characters that people miscopy.
BIP39 writes it as words instead. The entropy gets a checksum, its first
ENT/32 bits of SHA-256, and the bits are cut into 11-bit groups, each an
index into a list of 2048 words:

.. math::

   \text{words} = \frac{ENT + ENT/32}{11}, \qquad 128 \text{ bits} \to 12 \text{ words}.

A mistyped word is caught by the checksum unless the bits happen to match,
which for 12 words is 1 time in 16. The phrase then goes through
PBKDF2-HMAC-SHA512 with 2048 iterations, salted with ``"mnemonic"`` and an
optional passphrase, to give the 64-byte seed for BIP32. Every passphrase
gives a valid, different wallet, so a passphrase cannot be checked: a
forgotten one and a decoy look the same.

Teaching difference: the word list is not BIP39's English list but 2048
four-letter words generated by a rule (consonant, vowel, consonant,
vowel), in sorted order, so that index and word convert without a stored
list. :func:`mnemonic_to_seed` takes any phrase, so it reproduces BIP39's
published seeds for English phrases.
"""

import unicodedata
from collections.abc import Sequence

from blockchainkit.constants import BIP39_SALT_PREFIX
from blockchainkit.crypto.systems.hashing import sha256
from blockchainkit.wallets.systems.stretching import pbkdf2

_FIRST = "bdfghjklmnprstvz"
_SECOND = "aiou"
_THIRD = "dklmnrst"
_FOURTH = "aeio"

WORDLIST = tuple(a + b + c + d for a in _FIRST for b in _SECOND for c in _THIRD for d in _FOURTH)
"""tuple of str: The 2048 words, in sorted order; word i encodes the 11 bits of i."""

_INDEX = {word: i for i, word in enumerate(WORDLIST)}


def entropy_to_mnemonic(entropy: bytes) -> str:
    """Encode 16 to 32 bytes of entropy, plus its checksum, as 12 to 24 words.

    Examples
    --------
    >>> from blockchainkit.wallets import entropy_to_mnemonic
    >>> entropy_to_mnemonic(bytes(16)).split()[-2:]
    ['bada', 'bado']
    """
    if not isinstance(entropy, bytes) or len(entropy) not in (16, 20, 24, 28, 32):
        raise ValueError("entropy must be 16, 20, 24, 28 or 32 bytes")
    bits = 8 * len(entropy)
    checksum_bits = bits // 32
    checksum = sha256(entropy)[0] >> (8 - checksum_bits)
    value = int.from_bytes(entropy, "big") << checksum_bits | checksum
    words = (bits + checksum_bits) // 11
    return " ".join(WORDLIST[value >> 11 * (words - 1 - i) & 2047] for i in range(words))


def mnemonic_to_entropy(mnemonic: str) -> bytes:
    """Check a phrase's words and checksum, and return its entropy.

    Raises
    ------
    ValueError
        A word is not in the list, the length is wrong, or the checksum
        fails: the phrase was miscopied.
    """
    words = _words(mnemonic)
    value = 0
    for word in words:
        value = value << 11 | _INDEX[word]
    checksum_bits = len(words) * 11 // 33
    entropy = (value >> checksum_bits).to_bytes(4 * checksum_bits, "big")
    if value & (1 << checksum_bits) - 1 != sha256(entropy)[0] >> (8 - checksum_bits):
        raise ValueError("checksum mismatch: a word was miscopied")
    return entropy


def is_valid_mnemonic(mnemonic: str) -> bool:
    """True if every word is in the list and the checksum holds."""
    try:
        mnemonic_to_entropy(mnemonic)
    except (TypeError, ValueError):
        return False
    return True


def _words(mnemonic: str) -> Sequence[str]:
    if not isinstance(mnemonic, str):
        raise TypeError("mnemonic must be a string")
    words = mnemonic.split()
    if len(words) not in (12, 15, 18, 21, 24):
        raise ValueError("a mnemonic has 12, 15, 18, 21 or 24 words")
    unknown = [word for word in words if word not in _INDEX]
    if unknown:
        raise ValueError(f"not in the word list: {unknown[0]!r}")
    return words


def mnemonic_to_seed(mnemonic: str, passphrase: str = "") -> bytes:
    """The 64-byte BIP39 seed: PBKDF2-HMAC-SHA512 over 2048 iterations.

    The salt is ``"mnemonic" + passphrase``.

    Both strings are normalized to Unicode NFKD first. The phrase is not
    checked: BIP39 derives a seed from any string.

    Examples
    --------
    >>> from blockchainkit.wallets import mnemonic_to_seed
    >>> phrase = " ".join(["abandon"] * 11 + ["about"])  # BIP39 test vector
    >>> mnemonic_to_seed(phrase, "TREZOR").hex()[:16]
    'c55257c360c07c72'
    """
    if not isinstance(mnemonic, str) or not isinstance(passphrase, str):
        raise TypeError("mnemonic and passphrase must be strings")
    password = unicodedata.normalize("NFKD", mnemonic).encode()
    salt = unicodedata.normalize("NFKD", BIP39_SALT_PREFIX + passphrase).encode()
    return pbkdf2(password, salt, 2048, 64, "sha512")
